import catalog from "@/data/guides/catalog.json";
import editorial from "@/data/guides/editorial.json";
import { MIN_INDEXABLE_GUIDE_WORDS } from "@/lib/seo";

export type GuideVisual =
  | { type: "compare"; cornerLabel?: string; columns: string[]; rows: { label: string; cells: string[] }[]; caption?: string }
  | { type: "steps"; items: { title: string; text: string }[]; caption?: string }
  | { type: "checklist"; title?: string; items: string[]; caption?: string }
  | { type: "cards"; items: { title: string; text: string; tag?: string }[]; caption?: string }
  | { type: "timeline"; items: { label: string; text: string }[]; caption?: string }
  | { type: "callout"; tone?: "tip" | "warning"; title?: string; text: string }
  | { type: "image"; src: string; alt: string; width: number; height: number; caption?: string };

export type GuideSource = { label: string; href: string };

export type GuideSection = {
  title: string;
  body: string;
  /** Optional visual rendered right after the body. */
  visual?: GuideVisual;
};

export type GrowingGuide = {
  slug: string;
  citySlug?: string;
  cityLabel?: string;
  publishedAt?: string;
  title: string;
  summary: string;
  season?: string;
  readMinutes: number;
  sections: GuideSection[];
  /** Outside sources cited in the text; rendered as a list at the end. */
  sources?: GuideSource[];
  /** ISO date of the last substantive edit. */
  updatedAt?: string;
};

// catalog.json is regenerated by scripts/sync-launch-content.mjs; editorial.json is hand-written.
const guides = [
  ...(editorial.guides as GrowingGuide[]),
  ...(catalog.guides as GrowingGuide[]),
];

export function getAllGuides(): GrowingGuide[] {
  return guides;
}

export function getGuideBySlug(slug: string): GrowingGuide | undefined {
  return guides.find((g) => g.slug === slug);
}

export function getGuidesForCity(citySlug: string): GrowingGuide[] {
  return guides.filter((g) => g.citySlug === citySlug);
}

export const plantingCalendar = catalog.plantingCalendar as {
  monthNumber: number;
  tasks: string[];
}[];

export const torontoZoneLabel = catalog.zoneLabel as string;

export function isGuideIndexable(guide: GrowingGuide): boolean {
  const words = [guide.summary, ...guide.sections.map((s) => s.body)]
    .join(" ")
    .split(/\s+/).length;
  return words >= MIN_INDEXABLE_GUIDE_WORDS;
}
